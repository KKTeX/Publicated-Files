#!/usr/bin/env python3
"""Compile a TikZ figure into a ready-to-insert bundle and (optionally) check it
against the source image.

Input
  FIG.tikz            one tikzpicture environment, nothing else (no preamble).
  FIG.preamble.tex    optional: only \\usepackage / \\usetikzlibrary lines the
                      figure needs.  Picked up automatically if it sits next
                      to FIG.tikz (or pass --preamble).

Output (in --outdir, default: next to FIG.tikz)
  FIG.standalone.tex  compilable on its own (\\input{FIG.tikz})
  FIG.pdf / .png / .svg
  FIG.snippet.tex     figure environment + preamble lines to paste
  _check/FIG-compare.png   source | render side by side      (with --ref)
  _check/FIG-overlay.png   source (red) x render (blue)       (with --ref)
  _build/             intermediate files (safe to delete)

Usage
  build.py FIG.tikz [--preamble P.tex] [--ref IMG --ref-width-cm 12 [--zoom X0,Y0,X1,Y1]...]
           [--engine auto|lualatex|pdflatex|xelatex] [--dpi 220]
           [--caption TEXT] [--label fig:x] [--doc main.tex] [--outdir DIR]

  --zoom   also write _check/FIG-overlay-zoom.png: the overlay cut to this grid-cm
           region and enlarged, for judging small offsets and curve shapes.
           Repeatable: several regions give FIG-overlay-zoom-1.png, -2.png, ...
           Old zoom images are deleted at every --ref build, so what is in
           _check/ always belongs to the latest build.
  --doc    the host document; the snippet's \\input path is made relative to it
           (default: relative to the current directory).

How the overlay lines up: the picture is rendered a second time with its
bounding box forced to (0,0)-(ref width, ref height) in cm, so grid coordinates
land on the same pixels as in the reference.  The size printed for the normal
build is the picture's own tight bounding box, which is usually smaller.

The overlay is only meaningful when the picture was drawn in the grid frame
printed by grid.py (origin bottom-left, cm units, no global scale=).
"""
import argparse
import glob
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import (check_name, check_path, floats, need, positive, posix_rel,  # noqa: E402
                     read_text, run, strip_comments, write_text)

CJK = re.compile(r"[\u3000-\u30ff\u3400-\u9fff\uf900-\ufaff\uff00-\uffef]")
CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
MARK = "% generated by tikzify build.py"


def tex_errors(log):
    out, lines = [], log.splitlines()
    for i, l in enumerate(lines):
        if l.startswith("!") or re.match(r"^\S+\.(tex|tikz):\d+:", l):
            out.extend(lines[i:i + 4])
            out.append("")
    for l in lines:
        if "Missing character" in l:
            out.append("WARNING " + l.strip())
    return "\n".join(out[:80])


def pdf_size_cm(pdf):
    if shutil.which("pdfinfo") is None:
        return None
    r = run(["pdfinfo", pdf], check=False)
    m = re.search(r"Page size:\s+([\d.]+) x ([\d.]+) pts", r.stdout)
    if not m:
        return None
    return float(m.group(1)) / 72 * 2.54, float(m.group(2)) / 72 * 2.54


def doc(preamble_lines, body, engine, cjk, border="3pt", extra=""):
    pre = [MARK, "\\documentclass[border=%s]{standalone}" % border]
    if cjk:
        if engine == "lualatex":
            pre.append("\\usepackage{luatexja}")
        elif engine == "xelatex":
            pre.append("\\usepackage{xeCJK}")
    pre += preamble_lines
    if extra:
        pre.append(extra)
    return "\n".join(pre + ["\\begin{document}", body, "\\end{document}", ""])


def compile_tex(engine, texname, cwd):
    r = run([engine, "-interaction=nonstopmode", "-halt-on-error",
             "-file-line-error", "-output-directory=_build", texname],
            cwd=cwd, check=False)
    stem = os.path.splitext(texname)[0]
    logp = os.path.join(cwd, "_build", stem + ".log")
    log = read_text(logp) if os.path.exists(logp) else r.stdout
    pdf = os.path.join(cwd, "_build", stem + ".pdf")
    return (r.returncode == 0 and os.path.exists(pdf)), pdf, log


def check_source(path, text):
    m = CTRL.search(text)
    if m:
        line = text.count("\n", 0, m.start()) + 1
        sys.exit(f"error: {path}:{line} contains control character {m.group()!r}. "
                 "Write TeX files with an editor or printf '%s\\n', not echo "
                 "(zsh echo turns \\u.. into other characters).")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog=__doc__.split("Usage", 1)[1])
    ap.add_argument("fig")
    ap.add_argument("--preamble")
    ap.add_argument("--engine", default="auto",
                    choices=["auto", "lualatex", "pdflatex", "xelatex"])
    ap.add_argument("--ref")
    ap.add_argument("--ref-width-cm", type=float)
    ap.add_argument("--dpi", type=int, default=220)
    ap.add_argument("--caption", default="")
    ap.add_argument("--label")
    ap.add_argument("--outdir")
    ap.add_argument("--zoom", action="append", default=[])
    ap.add_argument("--doc")
    a = ap.parse_args()

    engine = "lualatex" if a.engine == "auto" else a.engine
    need(engine, "pdftoppm")
    fig = os.path.abspath(a.fig)
    if not os.path.isfile(fig):
        sys.exit(f"error: {a.fig} not found")
    name = os.path.splitext(os.path.basename(fig))[0]
    check_name(name)
    if a.ref:
        if not a.ref_width_cm:
            sys.exit("error: --ref needs --ref-width-cm (the width_cm printed by grid.py)")
        positive(a.ref_width_cm, "--ref-width-cm")
        if not os.path.isfile(a.ref):
            sys.exit(f"error: reference image {a.ref} not found")
        check_path(a.ref, "--ref")
        need("magick")
    zooms = [floats(z, 4, "--zoom") for z in a.zoom]
    if zooms and not a.ref:
        sys.exit("error: --zoom only works together with --ref")

    outdir = os.path.abspath(a.outdir or os.path.dirname(fig))
    src_dir = os.path.dirname(fig)
    pre_path = a.preamble or os.path.join(src_dir, name + ".preamble.tex")
    if a.preamble and not os.path.isfile(a.preamble):
        sys.exit(f"error: --preamble {a.preamble} not found")

    # Never clobber files we did not generate (e.g. the source drawing.svg/.png
    # sitting next to drawing.tikz, or another figure in --outdir).  Generated
    # files are recorded in a manifest; the check runs before anything is written.
    manifest = os.path.join(outdir, "_build", "generated.txt")
    ours = set(read_text(manifest).split("\n")) if os.path.exists(manifest) else set()
    products = [name + e for e in (".pdf", ".png", ".svg", ".standalone.tex", ".snippet.tex")]
    copies = []
    if src_dir != outdir:
        copies.append((fig, name + ".tikz"))
    if os.path.exists(pre_path) and os.path.dirname(os.path.abspath(pre_path)) != outdir:
        copies.append((pre_path, name + ".preamble.tex"))
    sa_path = os.path.join(outdir, name + ".standalone.tex")
    if os.path.exists(sa_path) and read_text(sa_path).startswith(MARK):
        ours |= set(products)             # _build/ was deleted but these are ours
    clash = [p for p in products + [d for _, d in copies]
             if os.path.exists(os.path.join(outdir, p)) and p not in ours]
    if clash:
        sys.exit("error: refusing to overwrite %s in %s (not generated by build.py). "
                 "Rename the .tikz or pass another --outdir." % (", ".join(clash), outdir))
    os.makedirs(os.path.join(outdir, "_build"), exist_ok=True)
    write_text(manifest, "\n".join(sorted((ours | set(products) | {d for _, d in copies}) - {""})))
    for s, d in copies:
        shutil.copy(s, os.path.join(outdir, d))

    preamble = []
    if os.path.exists(pre_path):
        ptext = read_text(pre_path)
        check_source(pre_path, ptext)
        preamble = [l.rstrip() for l in ptext.splitlines() if l.strip()]
    if not any(re.search(r"\\usepackage\s*(\[[^\]]*\])?\s*\{[^}]*\b(tikz|pgfplots|circuitikz|tikz-cd)\b",
                         strip_comments(l)) for l in preamble):
        preamble.insert(0, "\\usepackage{tikz}")

    body = read_text(fig)
    check_source(fig, body)
    code = strip_comments(body)
    if "\\documentclass" in code or "\\begin{document}" in code:
        sys.exit("error: FIG.tikz must contain only the tikzpicture, not a full document")
    cjk = bool(CJK.search(body))
    if cjk and engine == "pdflatex":
        print("WARNING: Japanese text with pdflatex -- the host document needs CJK support")

    # 1) the deliverable standalone build
    sa = name + ".standalone.tex"
    write_text(os.path.join(outdir, sa), doc(preamble, "\\input{%s.tikz}\\unskip" % name, engine, cjk))
    ok, pdf, log = compile_tex(engine, sa, outdir)
    if not ok:
        print("COMPILE FAILED\n" + tex_errors(log))
        sys.exit(1)
    warn = tex_errors(log)
    if warn:
        print(warn)
    shutil.copy(pdf, os.path.join(outdir, name + ".pdf"))
    run(["pdftoppm", "-png", "-r", str(a.dpi), "-singlefile", pdf, os.path.join(outdir, name)])
    svg = os.path.join(outdir, name + ".svg")
    if os.path.exists(svg):
        os.remove(svg)
    if shutil.which("pdftocairo") and run(["pdftocairo", "-svg", pdf, svg], check=False).returncode == 0:
        pass
    else:
        print("WARNING: SVG not written (pdftocairo missing or failed)")
    size = pdf_size_cm(pdf)
    if size:
        print(f"built  {outdir}/{name}.pdf  (tight size {size[0] - 0.21:.2f} x {size[1] - 0.21:.2f} cm "
              f"+ 3pt border; compare with the text width of the host document"
              + ("; smaller than --ref-width-cm is normal: this is the tight bbox" if a.ref else "") + ")")
    else:
        print(f"built  {outdir}/{name}.pdf")

    # 2) snippet to paste into the host document
    label = a.label or "fig:" + name
    snippet = ["% --- preamble (once per document) ---"]
    snippet += ["% " + l for l in preamble]
    if cjk:
        snippet.append("% (contains Japanese: host document must be (u)pLaTeX / LuaLaTeX-ja / XeCJK)")
    base = os.path.dirname(os.path.abspath(a.doc)) if a.doc else os.getcwd()
    tikz_rel = posix_rel(os.path.join(outdir, name + ".tikz"), base)
    snippet += ["% --- body (\\input path relative to " + (a.doc or "the current directory") + ") ---",
                "\\begin{figure}[htbp]",
                "  \\centering",
                "  \\input{%s}" % tikz_rel,
                "  \\caption{%s}" % a.caption,
                "  \\label{%s}" % label,
                "\\end{figure}", ""]
    write_text(os.path.join(outdir, name + ".snippet.tex"), "\n".join(snippet))

    # 3) visual check against the source
    if a.ref:
        chk = os.path.join(outdir, "_check")
        os.makedirs(chk, exist_ok=True)
        for old in glob.glob(os.path.join(chk, glob.escape(name) + "-overlay-zoom*.png")):
            os.remove(old)
        ref = os.path.abspath(a.ref)
        rw, rh = map(int, run(["magick", "identify", "-format", "%w %h", ref + "[0]"]).stdout.split())
        hcm = rh / rw * a.ref_width_cm
        frame = ("\\tikzset{every picture/.append style={execute at begin picture="
                 "{\\useasboundingbox (0cm,0cm) rectangle (%.4fcm,%.4fcm);}}}"
                 % (a.ref_width_cm, hcm))
        ov = name + ".overlay.tex"
        write_text(os.path.join(outdir, ov),
                   doc(preamble, "\\input{%s.tikz}\\unskip" % name, engine, cjk, border="0pt", extra=frame))
        ok, opdf, olog = compile_tex(engine, ov, outdir)
        os.remove(os.path.join(outdir, ov))
        if not ok:
            print("overlay build failed\n" + tex_errors(olog))
            sys.exit(1)
        dpi = rw / a.ref_width_cm * 2.54
        orender = os.path.join(outdir, "_build", name + "-ov")
        run(["pdftoppm", "-png", "-r", f"{dpi:.3f}", "-singlefile", opdf, orender])
        orender += ".png"
        overlay = os.path.join(chk, name + "-overlay.png")
        run(["magick",
             "(", ref + "[0]", "-colorspace", "Gray", "-resize", f"{rw}x{rh}!",
             "+level-colors", "rgb(225,30,30),white", ")",
             "(", orender, "-background", "white", "-alpha", "remove",
             "-resize", f"{rw}x{rh}!", "-colorspace", "Gray",
             "+level-colors", "rgb(20,60,230),white", ")",
             "-compose", "Multiply", "-composite", overlay])
        compare = os.path.join(chk, name + "-compare.png")
        h = 900
        run(["magick",
             "(", ref + "[0]", "-background", "white", "-alpha", "remove", "-resize", f"x{h}",
             "-gravity", "North", "-splice", "0x34", "-pointsize", "24",
             "-annotate", "+0+4", "source", ")",
             "(", orender, "-background", "white", "-alpha", "remove", "-resize", f"x{h}",
             "-gravity", "North", "-splice", "0x34", "-pointsize", "24",
             "-annotate", "+0+4", "TikZ", ")",
             "-bordercolor", "gray70", "-border", "2", "+append", compare])
        print(f"check  {overlay}\n       {compare}")
        ppc = rw / a.ref_width_cm
        for zi, (zx0, zy0, zx1, zy1) in enumerate(zooms, 1):
            zx0, zx1 = max(0.0, min(zx0, zx1)), min(a.ref_width_cm, max(zx0, zx1))
            zy0, zy1 = max(0.0, min(zy0, zy1)), min(hcm, max(zy0, zy1))
            w, hh = round((zx1 - zx0) * ppc), round((zy1 - zy0) * ppc)
            if w < 2 or hh < 2:
                print(f"WARNING: --zoom {a.zoom[zi - 1]} is empty or outside the reference; skipped")
                continue
            box = "%dx%d+%d+%d" % (w, hh, round(zx0 * ppc), round(rh - zy1 * ppc))
            zoom = os.path.join(chk, name + "-overlay-zoom%s.png" % ("" if len(zooms) == 1 else "-%d" % zi))
            run(["magick", overlay, "-crop", box, "+repage", "-resize", "1400x1000", zoom])
            print(f"       {zoom}")
        print("       overlay: red = only in source (missing), blue = only in TikZ (extra), "
              "dark = matches")
        if size and (size[0] - 0.21 > a.ref_width_cm * 1.15 or size[1] - 0.21 > hcm * 1.15):
            print("WARNING: picture is much larger than the source frame. Fine if labels sit "
                  "outside the source image (e.g. PDF text around an embedded picture); "
                  "otherwise the coordinates are probably not in grid cm")

    print(f"snippet {outdir}/{name}.snippet.tex")


if __name__ == "__main__":
    main()
